'use strict';
// REAL-AUDIO / REAL-PROVIDER integration test for Instagram voice messages.
// Not part of `npm test` (it needs Windows, and part B costs a fraction of a cent).
//
//   node tests/integration/instagram-voice-real.js
//
// Part A - REAL AUDIO FILES, provider MOCKED (always runs, no key needed):
//   real speech recorded with the local Windows voice (WAV) and re-encoded by Windows
//   Media Foundation to AAC in an MP4 container (.m4a, like Meta's voice clips), run
//   through the REAL Instagram workflow JSON (download -> Check Voice File ->
//   Transcribe Voice -> Read Transcript -> AI) in the emulator.
// Part B - REAL PROVIDER (runs only with a key): the same files plus French, Spanish,
//   Arabic and English speech generated by OpenRouter text-to-speech, transcribed by
//   the REAL OpenRouter speech-to-text endpoint with the exact multipart request the
//   workflow builds. The AI reply is still the emulator's scripted AI (the real chat
//   model is not called): only the instruction it receives is checked.
// Key: env OPENROUTER_API_KEY, or a file `.env.openrouter-test` in the project root
// containing OPENROUTER_API_KEY=... (git-ignored). The key is never printed or saved.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const assert = require('assert');

const ROOT = path.resolve(__dirname, '..', '..');
const IGT = require(path.join(ROOT, 'tests', 'instagram.test.js'));
const { env, post, voiceEv, all, aiFor, igTo, lockFree, noErrors, IB, A, IK } = IGT;
const OUT = fs.mkdtempSync(path.join(os.tmpdir(), 'lumiere-voice-'));
const PS1 = path.join(__dirname, 'transcode-m4a.ps1');

function readKey() {
  if (process.env.OPENROUTER_API_KEY) return process.env.OPENROUTER_API_KEY.trim();
  const f = path.join(ROOT, '.env.openrouter-test');
  if (!fs.existsSync(f)) return '';
  const m = /^\s*OPENROUTER_API_KEY\s*=\s*(\S+)\s*$/m.exec(fs.readFileSync(f, 'utf8'));
  return m ? m[1] : '';
}
const KEY = readKey();

const SAMPLES = {
  en: { say: "Hi, I would like to book a women's haircut tomorrow at ten in the morning, please.", words: /haircut|book/i },
  fr: { say: 'Bonjour, je voudrais réserver une coupe femme demain à dix heures, s’il vous plaît.', words: /coupe|réserver|demain/i },
  es: { say: 'Hola, quiero reservar un corte de mujer para mañana a las diez, por favor.', words: /corte|reservar|mañana/i },
  ar: { say: 'مرحبا، أريد حجز موعد لقص الشعر غدا الساعة العاشرة صباحا من فضلك.', words: /[؀-ۿ]{3,}/ },
};
const NAMES = { en: 'English', fr: 'French', es: 'Spanish', ar: 'Arabic' };
function toM4a(input, output, speak) {
  const args = ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', PS1, '-In', input, '-Out', output];
  if (speak) args.push('-Speak', speak);
  execFileSync('powershell.exe', args, { stdio: 'pipe' });
  return fs.readFileSync(output);
}
async function tts(lang) {
  const res = await fetch('https://openrouter.ai/api/v1/audio/speech', {
    method: 'POST', headers: { Authorization: 'Bearer ' + KEY, 'Content-Type': 'application/json' },
    body: JSON.stringify({ model: 'google/gemini-2.5-flash-tts', input: SAMPLES[lang].say, voice: 'Kore', response_format: 'wav' }),
  });
  if (!res.ok) throw new Error('text-to-speech HTTP ' + res.status + ': ' + (await res.text()).slice(0, 200));
  return Buffer.from(await res.arrayBuffer());
}
// Sends the workflow's own multipart request (from the emulator) to the real endpoint.
async function realStt(req) {
  const fd = new FormData();
  for (const f of req.form) {
    if (f.file) fd.append(f.name, new Blob([f.file.bytes], { type: f.file.mimeType }), f.file.fileName);
    else fd.append(f.name, f.value);
  }
  const res = await fetch(req.url, { method: 'POST', headers: { Authorization: 'Bearer ' + KEY }, body: fd });
  const body = await res.json().catch(() => ({}));
  return { status: res.status, body };
}

async function runOne(label, bytes, expectLang, mode) {
  const e = env({ seed: 7000 + Math.floor(Math.random() * 1000) });
  Object.assign(e.voice, { bytes, mime: 'audio/mp4' });
  let real = null;
  if (mode === 'real') {
    e.voice.result = () => { throw new Error('placeholder'); };
    const R = require(path.join(ROOT, 'tests', 'lib', 'runner.js'));
    // Intercept the transcription request: forward it to the real provider.
    const orig = R.Runner.prototype.http;
    R.Runner.prototype.http = async function (node, items, runIndex) {
      if (node.name !== 'Transcribe Voice') return orig.call(this, node, items, runIndex);
      const hook = this.env.hooks.http;
      this.env.hooks.http = async (req, run) => {
        if (req.url !== IB.VOICE.url) return hook(req, run);
        const t0 = Date.now();
        real = await realStt(req);
        real.ms = Date.now() - t0;
        real.sent = req.form.find((f) => f.file).file;
        if (real.status >= 400) throw new Error('Request failed with status code ' + real.status);
        return { statusCode: 200, body: real.body };
      };
      try { return await orig.call(this, node, items, runIndex); } finally { this.env.hooks.http = hook; }
    };
    try { await all(e, [() => post(e, [voiceEv(e, A)])]); } finally { R.Runner.prototype.http = orig; }
  } else {
    e.voice.result = { text: 'Mocked transcript.', language: 'english' };
    await all(e, [() => post(e, [voiceEv(e, A)])]);
  }
  noErrors(e);
  const call = aiFor(e, A)[0];
  const sent = mode === 'real' ? real && real.sent : e.rec.stt[0] && e.rec.stt[0].form.find((f) => f.file).file;
  const row = { label, mode, bytes: bytes.length, sentAs: sent ? sent.fileName + ' (' + sent.mimeType + ')' : '-', reachedAI: !!call };
  if (mode === 'real') {
    const b = (real && real.body) || {};
    Object.assign(row, { http: real && real.status, detected: b.language, transcript: String(b.text || '').trim(), seconds: b.duration, cost: b.usage && b.usage.cost, ms: real && real.ms });
    if (call) row.marker = (/detected language: ([A-Za-z]+)(, UNCERTAIN)?/.exec(call.prompt) || [])[0];
  }
  row.reply = (igTo(e, A).slice(-1)[0] || {}).text === IB.VOICE_FAILED_TEXT ? 'VOICE FAILED reply' : 'AI reply';
  lockFree(e, IK(A));
  return { row, call, expectLang };
}

(async () => {
  const results = [];
  let failures = 0;
  const check = (cond, msg) => { if (!cond) { failures++; console.log('  FAIL ' + msg); } };
  // Part A - real audio files, provider mocked.
  const enWav = path.join(OUT, 'en-sapi.wav'), enM4a = path.join(OUT, 'en-sapi.m4a');
  const files = { 'en-sapi.wav': null, 'en-sapi.m4a': toM4a(enWav, enM4a, SAMPLES.en.say) };
  files['en-sapi.wav'] = fs.readFileSync(enWav);
  console.log('Part A - REAL audio files (Windows voice; m4a re-encoded by Media Foundation), provider MOCKED');
  for (const [name, bytes] of Object.entries(files)) {
    const r = await runOne(name, bytes, 'en', 'mock');
    results.push(r.row);
    check(r.row.sentAs === (name.endsWith('.m4a') ? 'voice.m4a (audio/mp4)' : 'voice.wav (audio/wav)'), name + ': format recognised from the real bytes (' + r.row.sentAs + ')');
    check(r.row.reachedAI, name + ': reached the AI');
  }
  if (!KEY) {
    console.log('\nPart B - REAL PROVIDER: SKIPPED (no OPENROUTER_API_KEY / .env.openrouter-test)');
  } else {
    console.log('\nPart B - REAL PROVIDER (OpenRouter text-to-speech + speech-to-text ' + IB.VOICE.model + ')');
    const real = { 'en-sapi.m4a': ['en', files['en-sapi.m4a']] };
    for (const lang of ['en', 'fr', 'es', 'ar']) {
      const wav = await tts(lang);
      const wavPath = path.join(OUT, lang + '-tts.wav');
      fs.writeFileSync(wavPath, wav);
      real[lang + '-tts.wav'] = [lang, wav];
      real[lang + '-tts.m4a'] = [lang, toM4a(wavPath, path.join(OUT, lang + '-tts.m4a'))];
    }
    for (const [name, [lang, bytes]] of Object.entries(real)) {
      const r = await runOne(name, bytes, lang, 'real');
      results.push(r.row);
      check(r.row.http === 200, name + ': provider HTTP ' + r.row.http);
      check(r.row.reachedAI, name + ': reached the AI (' + r.row.reply + ')');
      check(SAMPLES[lang].words.test(r.row.transcript), name + ': transcript content');
      check(new RegExp('^detected language: ' + NAMES[lang] + '(, UNCERTAIN)?$').test(r.row.marker || ''), name + ': language passed to Yasmine = ' + r.row.marker);
      if (lang === 'ar') check(/[؀-ۿ]/.test(r.row.transcript), name + ': Arabic script');
    }
  }
  console.log('');
  for (const r of results) console.log(JSON.stringify(r));
  const cost = results.reduce((a, r) => a + (Number(r.cost) || 0), 0);
  if (KEY) console.log('\nreported speech-to-text cost for this run: $' + cost.toFixed(6));
  console.log(failures ? failures + ' check(s) FAILED' : 'ALL CHECKS PASSED');
  process.exit(failures ? 1 : 0);
})().catch((err) => { console.error('integration test error: ' + String(err && err.message || err).replace(/Bearer\s+\S+/g, 'Bearer <hidden>')); process.exit(1); });
